SELECT A.ID, A.EMAIL, A.FIRST_NAME, A.LAST_NAME
FROM DEVELOPERS AS A, (
    SELECT SUM(CODE) AS FE
    FROM SKILLCODES
    WHERE CATEGORY = 'Front End'
)AS B
WHERE B.FE&A.SKILL_CODE > 0
ORDER BY A.ID

